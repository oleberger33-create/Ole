def ansage(tl, text, say=None, gap=0.6):
    tl.sfx("gong")
    tl.wait(1.25)
    tl.line("A", text, say=say, gap=gap)


def halle_reset(tl, cranking=True):
    """Zurück in die Halle: Die Kamera steht noch ganz nah auf KURTs Bildschirm (der Film läuft dort weiter)
    und fährt danach heraus – der Aufrufer setzt dafür eine Einstellung mit dur > 0, z. B. 1.4 s 'io'."""
    tl.scene("halle")
    tl.shot(860, 685.6, 9.0)
    tl.st("fussel", vis=0, brow="none")
    tl.st("kurt", vis=1, screen="film")
    tl.st("broesel", vis=1, crank=1 if cranking else 0)
    tl.key("broesel", x=CRATE_X, y=CRATE_Y, flip=-1, s=1.25, lid=0.55, brow=0)
    tl.st("gurrmann", vis=0)
    tl.st("crowd", mode="off")
    tl.st("train", vis=0)


def into_screen(tl, nr, name, say):
    """Kamera fährt in KURTs Bildschirm (Zoom beschleunigt, logarithmisch). KURT zeigt schon den Filmtitel,
    der Schnitt auf die Filmtitel-Karte sitzt bildgenau auf seinem Schirm, danach öffnet sich der Rand."""
    tl.sfx("whoosh", off=0.2)
    tl.st("filmtitel", nr=nr, name=name)
    tl.key("cam", x=860, y=685.6, dur=0.6, ease="io")   # Mitte von KURTs Schirm
    tl.key("cam", z=9.0, dur=1.35, ease="in")      # endet genau am Schnitt: die Fahrt läuft in die Karte weiter
    tl.st("kurt", screen="title", off=0.9)
    tl.wait(1.35)
    tl.scene("filmtitel")
    tl.shot(960, 540, 1.0)
    tl.sfx("blip")
    tl.wait(0.4)
    tl.line("K", f"Film {nr}. {name.title()}.", say=say, gap=0.9)


def iris_open(tl, scene, cx=960, cy=540):
    """Irisblende auf; (cx, cy) = Mittelpunkt im Bild, der Kreis wächst bis über die fernste Ecke."""
    tl.scene(scene)
    tl.st("fussel", brow="none")
    tl.key("gurrmann", brow=0)
    rmax = max(((cx - ex) ** 2 + (cy - ey) ** 2) ** 0.5 for ex in (0, 1920) for ey in (0, 1080)) + 40
    tl.key("iris", r=0, x=cx, y=cy)
    tl.key("iris", r=rmax, dur=1.1, ease="out")
    tl.sfx("iris")


